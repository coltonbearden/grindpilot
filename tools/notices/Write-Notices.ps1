# Writes THIRD-PARTY-NOTICES.md for what a build ships: every NuGet package and runtime pack in the publish folder's
# GrindPilot.deps.json, each with its licence read from the package itself (its .nuspec and the licence and notice files
# inside it), and the Rust crates linked into Velopack's helpers (tools/velopack/crate-notices.md, which must be made
# for the commit tools/velopack/source.json names). The release workflow ships the result in the package and attaches
# it to the release; CI compares it with the committed copy. See docs/build.md, "Third-party notices".
#
#   ./tools/notices/Write-Notices.ps1 -Publish <publish folder> [-Out THIRD-PARTY-NOTICES.md]
param(
    [Parameter(Mandatory)][string]$Publish,
    [string]$Repo = (Resolve-Path (Join-Path $PSScriptRoot '../..')).Path,
    [string]$Out = (Join-Path $Repo 'THIRD-PARTY-NOTICES.md'),
    [string]$Packages = $(if ($env:NUGET_PACKAGES) { $env:NUGET_PACKAGES } else { Join-Path $HOME '.nuget/packages' })
)
$ErrorActionPreference = 'Stop'

function Read-Text([string]$path) { ([IO.File]::ReadAllText($path) -replace "`r`n", "`n").Trim() }

$source = Get-Content (Join-Path $Repo 'tools/velopack/source.json') -Raw | ConvertFrom-Json
$crates = Join-Path $Repo 'tools/velopack/crate-notices.md'
$crateText = Read-Text $crates
if (-not $crateText.Contains("Velopack commit: $($source.commit)")) {
    throw "tools/velopack/crate-notices.md wasn't made for Velopack $($source.commit); run tools/notices/Write-CrateNotices.ps1."
}

$deps = Get-Content (Join-Path $Publish 'GrindPilot.deps.json') -Raw | ConvertFrom-Json
$libs = [System.Collections.Generic.List[object]]@($deps.libraries.PSObject.Properties | Where-Object { $_.Value.type -in 'package', 'runtimepack' })
# Ordinal order, so the file is byte-identical on every machine.
$libs.Sort([Comparison[object]] { param($a, $b) [string]::CompareOrdinal(($a.Name -replace '^runtimepack\.', ''), ($b.Name -replace '^runtimepack\.', '')) })

$standard = [System.Collections.Generic.SortedSet[string]]::new()
$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine('# Third-party notices')
[void]$sb.AppendLine()
[void]$sb.AppendLine('GrindPilot is MIT-licensed (LICENSE). Its installer and program folder also carry the software below, each under')
[void]$sb.AppendLine('its own licence, read from the package itself. Generated by tools/notices/Write-Notices.ps1 from the build''s')
[void]$sb.AppendLine('GrindPilot.deps.json; the copy inside each release is the one for that release.')
[void]$sb.AppendLine()
[void]$sb.AppendLine('## .NET packages and runtime')
[void]$sb.AppendLine()
[void]$sb.AppendLine('| Package | Version | Licence | Copyright |')
[void]$sb.AppendLine('|---|---|---|---|')
$entries = foreach ($lib in $libs) {
    $id, $version = $lib.Name -replace '^runtimepack\.', '' -split '/'
    $dir = Join-Path $Packages ("{0}/{1}" -f $id.ToLowerInvariant(), $version)
    $nuspec = Get-ChildItem $dir -Filter '*.nuspec' -ErrorAction SilentlyContinue | Select-Object -First 1
    if (-not $nuspec) { throw "No .nuspec for $id $version in $Packages" }
    [xml]$x = Get-Content $nuspec.FullName
    $m = $x.package.metadata
    $licence = if ($m.license -and $m.license.type -eq 'expression') { $m.license.'#text' }
               elseif ($m.license -and $m.license.type -eq 'file') { "see $($m.license.'#text')" }
               elseif ($m.licenseUrl) { $m.licenseUrl } else { 'not stated' }
    $files = Get-ChildItem $dir -File | Where-Object Name -match '^(?i)(licen[cs]e|third-party-notices|notice|copying)' | Sort-Object Name
    [pscustomobject]@{ Id = $id; Version = $version; Licence = $licence; Copyright = "$($m.copyright)".Trim(); Url = "$($m.projectUrl)"; Files = $files }
}
foreach ($e in $entries) { [void]$sb.AppendLine("| $($e.Id) | $($e.Version) | $($e.Licence) | $($e.Copyright) |") }
[void]$sb.AppendLine()

$printed = @{}
foreach ($e in $entries) {
    [void]$sb.AppendLine("### $($e.Id) $($e.Version)")
    [void]$sb.AppendLine()
    [void]$sb.AppendLine("Licence: $($e.Licence)$(if ($e.Copyright) { ". $($e.Copyright)" })$(if ($e.Url) { ". $($e.Url)" })")
    [void]$sb.AppendLine()
    if ($e.Files) {
        foreach ($f in $e.Files) {
            $t = Read-Text $f.FullName
            $h = [Convert]::ToHexString([Security.Cryptography.SHA256]::HashData([Text.Encoding]::UTF8.GetBytes($t)))
            if ($printed.ContainsKey($h)) {
                [void]$sb.AppendLine("$($f.Name): the same text as $($printed[$h]), above.")
                [void]$sb.AppendLine()
                continue
            }
            $printed[$h] = "$($e.Id)'s $($f.Name)"
            [void]$sb.AppendLine("$($f.Name), from the package:")
            [void]$sb.AppendLine()
            [void]$sb.AppendLine('```text')
            [void]$sb.AppendLine($t)
            [void]$sb.AppendLine('```')
            [void]$sb.AppendLine()
        }
    } elseif ($e.Licence -eq 'MIT') {
        # The package states MIT by expression only: the MIT text with the package's own copyright line.
        $mit = (Read-Text (Join-Path $PSScriptRoot 'licenses/MIT.txt')).Replace('Copyright (c) <year> <copyright holders>', $e.Copyright)
        $h = [Convert]::ToHexString([Security.Cryptography.SHA256]::HashData([Text.Encoding]::UTF8.GetBytes($mit)))
        if ($printed.ContainsKey($h)) {
            [void]$sb.AppendLine("The MIT licence, with the same copyright line as $($printed[$h]), above.")
        } else {
            $printed[$h] = $e.Id
            [void]$sb.AppendLine('```text')
            [void]$sb.AppendLine($mit)
            [void]$sb.AppendLine('```')
        }
        [void]$sb.AppendLine()
    } elseif ($e.Licence -match '^[A-Za-z0-9.\-]+$' -and (Test-Path (Join-Path $PSScriptRoot "licenses/$($e.Licence).txt"))) {
        [void]$standard.Add($e.Licence)
        [void]$sb.AppendLine("The package states $($e.Licence) by expression; its text is under ""Standard licence texts"" below.")
        [void]$sb.AppendLine()
    } else {
        [void]$sb.AppendLine("The package names its licence by link only: $($e.Licence)")
        [void]$sb.AppendLine()
    }
}

[void]$sb.AppendLine('## Velopack''s helpers')
[void]$sb.AppendLine()
[void]$sb.AppendLine("Setup.exe, Update.exe and the stub are built from Velopack's MIT source at $($source.commit), with")
[void]$sb.AppendLine('tools/velopack/no-process-scan.patch applied (tools/velopack/LICENSE-velopack.txt is Velopack''s licence). The Rust')
[void]$sb.AppendLine('crates they link follow.')
[void]$sb.AppendLine()
# The crate list, one heading level down.
[void]$sb.AppendLine(($crateText -replace '(?m)^(#+) ', '#$1 '))
[void]$sb.AppendLine()
foreach ($m in [regex]::Matches($crateText, '(?m)^- [^:]+: (.+)$')) {
    foreach ($id in ($m.Groups[1].Value -split '[ /()]+' | Where-Object { $_ -and $_ -notin 'OR', 'AND' })) {
        if (Test-Path (Join-Path $PSScriptRoot "licenses/$id.txt")) { [void]$standard.Add($id) }
    }
}

[void]$sb.AppendLine('## Standard licence texts')
[void]$sb.AppendLine()
[void]$sb.AppendLine('For the packages and crates above that state a licence by expression and ship no text of their own (from SPDX''s')
[void]$sb.AppendLine('licence list).')
[void]$sb.AppendLine()
foreach ($id in $standard) {
    [void]$sb.AppendLine("### $id")
    [void]$sb.AppendLine()
    [void]$sb.AppendLine('```text')
    [void]$sb.AppendLine((Read-Text (Join-Path $PSScriptRoot "licenses/$id.txt")))
    [void]$sb.AppendLine('```')
    [void]$sb.AppendLine()
}

$text = ($sb.ToString() -replace "`r`n", "`n").TrimEnd() + "`n"
[IO.File]::WriteAllText($Out, $text, [Text.UTF8Encoding]::new($false))
"notices: $($entries.Count) .NET packages and runtime packs; standard texts: $(($standard) -join ', '); $([math]::Round($text.Length / 1KB)) KB -> $Out"
