# Writes tools/velopack/crate-notices.md: every Rust crate linked into Velopack's helpers (update, setup, stub) as
# this repo builds them, with each crate's licence as the crate itself states it and the licence texts the crates
# ship. Run it whenever tools/velopack/source.json names a new commit (docs/build.md, "Third-party notices");
# Write-Notices.ps1 refuses a crate list made for another commit.
#
#   ./tools/notices/Write-CrateNotices.ps1 -VelopackSource <a checkout of Velopack at source.json's commit>
#
# It runs `cargo metadata` (no build). Point CARGO_HOME at a scratch folder to keep the downloads out of your own.
param(
    [Parameter(Mandatory)][string]$VelopackSource,
    [string]$Repo = (Resolve-Path (Join-Path $PSScriptRoot '../..')).Path,
    [string]$Out = (Join-Path $Repo 'tools/velopack/crate-notices.md')
)
$ErrorActionPreference = 'Stop'
$PSNativeCommandUseErrorActionPreference = $true

$source = Get-Content (Join-Path $Repo 'tools/velopack/source.json') -Raw | ConvertFrom-Json
$head = (git -C $VelopackSource rev-parse HEAD).Trim()
if ($head -ne $source.commit) { throw "The checkout is at $head; source.json names $($source.commit)." }

$json = cargo metadata --format-version 1 --locked --filter-platform x86_64-pc-windows-msvc --features windows `
    --manifest-path (Join-Path $VelopackSource 'src/bins/Cargo.toml') 2>$null
$meta = ($json -join "`n") | ConvertFrom-Json -Depth 64
$packages = @{}
foreach ($p in $meta.packages) { $packages[$p.id] = $p }
$nodes = @{}
foreach ($n in $meta.resolve.nodes) { $nodes[$n.id] = $n }

# The helpers are three binaries of velopack_bins: everything it links (normal dependencies) and everything that
# generates code into it (build dependencies, proc-macros), never dev-dependencies.
$rootPkg = $meta.packages | Where-Object name -eq 'velopack_bins' | Select-Object -First 1
$seen = [System.Collections.Generic.HashSet[string]]::new()
$queue = [System.Collections.Generic.Queue[string]]::new()
$queue.Enqueue($rootPkg.id)
while ($queue.Count -gt 0) {
    $id = $queue.Dequeue()
    if (-not $seen.Add($id)) { continue }
    foreach ($d in $nodes[$id].deps) {
        # A normal dependency's kind is null; keep any edge that isn't dev-only.
        if (@($d.dep_kinds | Where-Object { $_.kind -ne 'dev' }).Count -gt 0) { $queue.Enqueue($d.pkg) }
    }
}

$crates = foreach ($id in $seen) {
    $p = $packages[$id]
    $dir = Split-Path $p.manifest_path
    $local = -not $p.source
    $texts = @()
    $files = if ($local) {
        # Velopack's own crates: the repository's licence.
        Get-ChildItem $VelopackSource -File | Where-Object Name -match '^(?i)(licen[cs]e|copying|notice)'
    } else {
        Get-ChildItem $dir -File | Where-Object Name -match '^(?i)(licen[cs]e|copying|notice|unlicense)'
    }
    if ($p.license_file) { $files = @(Get-Item (Join-Path $dir $p.license_file)) + @($files) }
    foreach ($f in ($files | Sort-Object FullName -Unique)) {
        $t = ([IO.File]::ReadAllText($f.FullName) -replace "`r`n", "`n").Trim()
        if ($t) { $texts += $t }
    }
    [pscustomobject]@{
        Name = $p.name; Version = $p.version
        License = if ($p.license) { $p.license } elseif ($p.license_file) { "see $($p.license_file)" } else { 'not stated' }
        Repository = $p.repository; Texts = $texts; Local = $local
    }
}
# Ordinal order, so the file is byte-identical on every machine.
$list = [System.Collections.Generic.List[object]]@($crates)
$list.Sort([Comparison[object]] { param($a, $b) [string]::CompareOrdinal("$($a.Name) $($a.Version)", "$($b.Name) $($b.Version)") })
$crates = $list

$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine('# Rust crates in Velopack''s helpers')
[void]$sb.AppendLine()
[void]$sb.AppendLine("Velopack commit: $($source.commit) (tag $($source.tag)), target x86_64-pc-windows-msvc, ``velopack_bins`` with")
[void]$sb.AppendLine('feature `windows`: every crate linked into `update.exe`, `setup.exe` and `stub.exe`, or generating code into them.')
[void]$sb.AppendLine('Each licence is as the crate states it; the texts below are the files the crates ship, each printed once.')
[void]$sb.AppendLine('Generated by tools/notices/Write-CrateNotices.ps1.')
[void]$sb.AppendLine()
[void]$sb.AppendLine('| Crate | Version | Licence | Repository |')
[void]$sb.AppendLine('|---|---|---|---|')
foreach ($c in $crates) { [void]$sb.AppendLine("| $($c.Name) | $($c.Version) | $($c.License) | $($c.Repository) |") }
[void]$sb.AppendLine()

$byText = [ordered]@{}
foreach ($c in $crates) {
    foreach ($t in $c.Texts) {
        $h = [Convert]::ToHexString([Security.Cryptography.SHA256]::HashData([Text.Encoding]::UTF8.GetBytes($t)))
        if (-not $byText.Contains($h)) { $byText[$h] = [pscustomobject]@{ Text = $t; Crates = [System.Collections.Generic.List[string]]::new() } }
        $byText[$h].Crates.Add("$($c.Name) $($c.Version)")
    }
}
$missing = $crates | Where-Object { $_.Texts.Count -eq 0 }
[void]$sb.AppendLine('## Licence texts the crates ship')
[void]$sb.AppendLine()
foreach ($entry in $byText.Values) {
    [void]$sb.AppendLine("### Shipped by: $(($entry.Crates | Sort-Object -Unique) -join ', ')")
    [void]$sb.AppendLine()
    [void]$sb.AppendLine('```text')
    [void]$sb.AppendLine($entry.Text)
    [void]$sb.AppendLine('```')
    [void]$sb.AppendLine()
}
if ($missing) {
    [void]$sb.AppendLine('## Crates that ship no licence file')
    [void]$sb.AppendLine()
    [void]$sb.AppendLine('These state their licence only by expression; the standard texts are in THIRD-PARTY-NOTICES.md, "Standard licence texts".')
    [void]$sb.AppendLine()
    foreach ($c in $missing) { [void]$sb.AppendLine("- $($c.Name) $($c.Version): $($c.License)") }
    [void]$sb.AppendLine()
}
$text = $sb.ToString() -replace "`r`n", "`n"
[IO.File]::WriteAllText($Out, $text, [Text.UTF8Encoding]::new($false))
"crates: $($crates.Count); distinct licence texts: $($byText.Count); without a file: $(@($missing).Count); licences: $((($crates.License | Sort-Object -Unique) -join '; '))"
